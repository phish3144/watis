#!/usr/bin/env node
// Builds the browser extension (ADR 0010) into out/extension/chromium (Chrome, Edge) and
// out/extension/firefox. With --pack, also zips both into out/extension/*.zip for the stores.
//
// Several Vite builds rather than one, because the pieces are different kinds of JavaScript:
//   - the pages (panel, host frame) and their workers are ES modules;
//   - content scripts and the background must be classic scripts — Chromium runs content
//     scripts as plain scripts and the background has to work as a classic service worker and as
//     a Firefox event page — so each is an IIFE of its own;
//   - the page shims are the desktop's shim *strings*, written out as literal source: WhatsApp's
//     CSP forbids eval in the page world, so a string could never be run from there.

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'
import { build } from 'vite'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'
import { zipDirectory } from './lib/zip.mjs'
import {
  SQLITE,
  TESSERACT_COMPONENTS,
  bsd3,
  collectPackages,
  mit,
  writeNotices,
} from './third-party-notices.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'out', 'extension')
const stage = join(out, 'chromium')
const pack = process.argv.includes('--pack')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

const alias = { '@shared': join(root, 'src', 'shared') }
const define = { 'process.env.NODE_ENV': JSON.stringify('production') }
/** Every npm package that ends up in one of the bundles, for the licence notices. */
const bundled = new Set()

/** Imports a dependency-free TypeScript module by transpiling it in memory. */
async function importTs(file) {
  const source = readFileSync(join(root, file), 'utf8')
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  })
  return import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`)
}

/** zod ships comments Rollup cannot place; the warning is about their code, not ours. */
function quietDependencyWarnings(warning, warn) {
  if (warning.code === 'INVALID_ANNOTATION' && String(warning.id ?? '').includes('node_modules'))
    return
  warn(warning)
}

rmSync(out, { recursive: true, force: true })
mkdirSync(stage, { recursive: true })

// 1. Pages: the panel and the hidden host frame, with the archive worker.
await build({
  configFile: false,
  root: join(root, 'src', 'extension'),
  base: './',
  logLevel: 'warn',
  plugins: [react(), tailwindcss(), collectPackages(bundled)],
  resolve: { alias },
  define,
  worker: { format: 'es', plugins: () => [collectPackages(bundled)] },
  build: {
    outDir: stage,
    emptyOutDir: false,
    target: 'es2022',
    // Store reviewers read the code; unminified output is what makes that review possible.
    minify: false,
    sourcemap: false,
    // The WASM files are large and must stay files: inlining them as base64 would bloat the
    // bundle and break streaming compilation.
    assetsInlineLimit: 0,
    rollupOptions: {
      input: {
        panel: join(root, 'src', 'extension', 'panel.html'),
        host: join(root, 'src', 'extension', 'host.html'),
      },
      onwarn: quietDependencyWarnings,
    },
  },
})

// 2. Classic scripts, one IIFE each.
const scripts = [
  ['src/extension/page/bridge-entry.ts', 'page/bridge.js'],
  ['src/extension/page/page-config.ts', 'page/shims.js'],
  ['src/extension/content/relay.ts', 'content/relay.js'],
  ['src/extension/background/background.ts', 'background.js'],
]
for (const [entry, fileName] of scripts) {
  await build({
    configFile: false,
    logLevel: 'warn',
    plugins: [collectPackages(bundled)],
    resolve: { alias },
    define,
    build: {
      outDir: stage,
      emptyOutDir: false,
      target: 'es2022',
      minify: false,
      sourcemap: false,
      lib: {
        entry: join(root, entry),
        formats: ['iife'],
        name: '__watisExtension',
        fileName: () => fileName,
      },
      rollupOptions: {
        output: { extend: true, inlineDynamicImports: true },
        onwarn: quietDependencyWarnings,
      },
    },
  })
}

// 3. The desktop's page shims, as literal source ahead of the page-config listener. The audio
//    output shim stays behind: a browser chooses its own output device.
const { NOTIFICATION_SHIM, ENTER_KEY_SHIM } = await importTs('src/preload/wa-notification-shim.ts')
const { MEDIA_VIEWER_SHIM } = await importTs('src/preload/wa-media-shim.ts')
const shimsFile = join(stage, 'page', 'shims.js')
writeFileSync(
  shimsFile,
  [
    '// Generated by scripts/build-extension.mjs from src/preload/wa-*-shim.ts. Do not edit.',
    // Each shim is an `(() => …)()` without a trailing semicolon. Joined by newlines alone, the
    // second one's parentheses would call the first one's result — so every piece is terminated.
    ...[NOTIFICATION_SHIM, ENTER_KEY_SHIM, MEDIA_VIEWER_SHIM].map((shim) => `${shim.trim()};`),
    readFileSync(shimsFile, 'utf8'),
  ].join('\n'),
)

// 4. Icons, from the same sources as the desktop app.
mkdirSync(join(stage, 'icons'), { recursive: true })
for (const size of [16, 32, 48, 128]) {
  cpSync(join(root, 'build', `icon-${size}.png`), join(stage, 'icons', `icon-${size}.png`))
}

// 5. Text recognition and PDF text, shipped inside the package: tesseract.js's worker and its SIMD
//    core, the German and English language data the desktop ships too, and pdf.js's worker. Nothing
//    is fetched from a CDN at run time (CLAUDE.md, "Datenschutz und Netz").
const ocr = join(stage, 'ocr')
mkdirSync(join(ocr, 'lang'), { recursive: true })
for (const file of ['worker.min.js', 'worker.min.js.LICENSE.txt']) {
  cpSync(join(root, 'node_modules', 'tesseract.js', 'dist', file), join(ocr, file))
}
cpSync(
  join(root, 'node_modules', 'tesseract.js-core', 'tesseract-core-simd-lstm.wasm.js'),
  join(ocr, 'tesseract-core-simd-lstm.wasm.js'),
)
for (const lang of ['deu', 'eng']) {
  cpSync(
    join(root, 'resources', 'tessdata', `${lang}.traineddata`),
    join(ocr, 'lang', `${lang}.traineddata`),
  )
}
cpSync(
  join(root, 'node_modules', 'pdfjs-dist', 'legacy', 'build', 'pdf.worker.min.mjs'),
  join(ocr, 'pdf.worker.min.mjs'),
)

// 6. Transcription: whisper.cpp as WASM, its Emscripten glue kept as a file of its own — its threads
//    start workers from their own URL, which a bundled copy would not have. The model is not in
//    the package; it is downloaded on a click (src/extension/panel/transcribe.ts).
mkdirSync(join(stage, 'whisper'), { recursive: true })
cpSync(
  join(root, 'node_modules', '@transcribe', 'shout', 'src', 'shout', 'shout.wasm.js'),
  join(stage, 'whisper', 'shout.wasm.js'),
)

// The licence texts of all of it: the packages the bundles took in, the files copied above, and what
// those files contain without being packages of their own.
writeNotices({
  root,
  file: join(stage, 'THIRD_PARTY_NOTICES.txt'),
  product: 'WatIs? (browser extension)',
  packages: new Set([
    ...bundled,
    'tesseract.js',
    'tesseract.js-core',
    // Inside tesseract.js's prebuilt worker (its source map lists them).
    'base64-js',
    'bmp-js',
    'idb-keyval',
    'is-url',
    'regenerator-runtime',
    'wasm-feature-detect',
    'zlibjs',
    'pdfjs-dist',
    '@transcribe/shout',
    '@sqlite.org/sqlite-wasm',
  ]),
  extras: [
    SQLITE,
    {
      name: "buffer (inside tesseract.js's worker)",
      licence: 'MIT',
      text: mit('Copyright (c) Feross Aboukhadijeh, and other contributors.'),
    },
    {
      name: "ieee754 (inside tesseract.js's worker)",
      licence: 'BSD-3-Clause',
      text: bsd3('Copyright 2008 Fair Oaks Labs, Inc.'),
    },
    {
      name: 'whisper.cpp (inside @transcribe/shout)',
      licence: 'MIT',
      text: mit('Copyright (c) 2023-2024 The ggml authors'),
    },
    ...TESSERACT_COMPONENTS,
    {
      name: 'OpenAI Whisper model weights (downloaded on request, not part of this package)',
      licence: 'MIT',
      text: mit('Copyright (c) 2022 OpenAI'),
    },
  ],
})

// 7. One manifest per browser. Firefox gets a copy of the same files.
const { buildManifest } = await importTs('src/extension/manifest.ts')
const firefox = join(out, 'firefox')
cpSync(stage, firefox, { recursive: true })
for (const [browser, dir] of [
  ['chromium', stage],
  ['firefox', firefox],
]) {
  writeFileSync(
    join(dir, 'manifest.json'),
    `${JSON.stringify(buildManifest(browser, pkg.version), null, 2)}\n`,
  )
}

// 8. Archives for the stores. No question mark in a file name, ever (CLAUDE.md).
if (pack) {
  zipDirectory(stage, join(out, `watis-${pkg.version}-chromium.zip`))
  zipDirectory(firefox, join(out, `watis-${pkg.version}-firefox.zip`))
}

for (const dir of [stage, firefox]) {
  if (!existsSync(join(dir, 'manifest.json'))) throw new Error(`no manifest in ${dir}`)
}
console.log(`ok    extension ${pkg.version} -> ${out}${pack ? ' (packed)' : ''}`)
